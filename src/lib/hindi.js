export const isHindi = new URLSearchParams(window.location.search).get("l") === "hi";

export function t(text) {
  if (!isHindi) return text;
  return COPY[text] ?? text;
}

function translateValue(value) {
  const trimmed = value.trim();
  const hindi = COPY[trimmed];
  if (!hindi) return value;
  const lead = value.match(/^\s*/)[0];
  const tail = value.match(/\s*$/)[0];
  return lead + hindi + tail;
}

export function applyHindi(root) {
  if (!isHindi || !root) return;

  const textNodes = [];
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  while (walker.nextNode()) textNodes.push(walker.currentNode);
  for (const node of textNodes) {
    const parent = node.parentElement;
    if (!parent || parent.closest("script, style")) continue;
    node.nodeValue = translateValue(node.nodeValue);
  }

  for (const el of root.querySelectorAll("[alt], [aria-label]")) {
    for (const attr of ["alt", "aria-label"]) {
      const value = el.getAttribute(attr);
      if (value) el.setAttribute(attr, translateValue(value));
    }
  }

  for (const meta of document.querySelectorAll(
    'meta[name="description"], meta[property="og:description"], meta[name="twitter:description"]',
  )) {
    const content = meta.getAttribute("content");
    if (content) meta.setAttribute("content", translateValue(content));
  }
}
